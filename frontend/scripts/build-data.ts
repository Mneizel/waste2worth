/**
 * Regenerates the bundled offline catalogue and its placeholder artwork from the
 * backend seed. Run: `npm run gen:data`. Commits `src/data/catalogue.ts` and
 * `public/media/**` so the static build needs no backend.
 */
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { BOTTLE_VARIANTS } from '../../backend/src/seed/bottleSizes';
import { IDEAS as SEED_IDEAS } from '../../backend/src/seed/ideas';
import type { IdeaDetail, Variant } from '../src/lib/types';

const here = dirname(fileURLToPath(import.meta.url));
const FRONTEND = resolve(here, '..');
const MEDIA = resolve(FRONTEND, 'public/media');

// ---------------------------------------------------------------- data ------

const VARIANTS: Variant[] = BOTTLE_VARIANTS.map((v) => ({
  id: `var-${v.key}`,
  key: v.key,
  categoryKey: 'bottle',
  label: v.label,
  materialType: v.materialType,
  volumeMl: v.volumeMl,
  heightMm: v.heightMm,
  diameterMm: v.diameterMm,
  region: v.region,
  typicalContents: v.typicalContents,
  isCommon: v.isCommon,
  sortOrder: v.sortOrder,
  notes: v.notes,
}));

const IDEAS: IdeaDetail[] = SEED_IDEAS.map((idea) => ({
  id: `idea-${idea.slug}`,
  slug: idea.slug,
  title: idea.title,
  summary: idea.summary,
  difficulty: idea.difficulty,
  estimatedMinutes: idea.estimatedMinutes,
  minAge: idea.minAge,
  safetyNotes: idea.safetyNotes ?? '',
  thumbnailUrl: `media/ideas/${idea.slug}-thumb.svg`,
  finalImageUrl: `media/ideas/${idea.slug}-final.svg`,
  model3dUrl: `media/models/${idea.slug}.glb`,
  model3dPreviewUrl: `media/ideas/${idea.slug}-3d.svg`,
  tools: idea.tools.map((t, i) => ({
    id: `tool-${idea.slug}-${i}`,
    kind: t.kind,
    name: t.name,
    imageUrl: '',
    quantity: t.quantity ?? '1',
    optional: t.optional ?? false,
    note: t.note ?? '',
  })),
  steps: idea.steps.map((s, i) => ({
    stepNumber: i + 1,
    title: s.title,
    instruction: s.instruction,
    imageUrl: `media/steps/${idea.slug}-${i + 1}.svg`,
    tip: s.tip ?? '',
    warning: s.warning ?? '',
    icon: s.icon ?? '',
  })),
  variantKeys: idea.variantKeys,
}));

const catalogue = `// GENERATED by scripts/build-data.ts — do not edit by hand.
// Regenerate with: npm run gen:data
import type { IdeaDetail, Variant } from '../lib/types';

export const VARIANTS: Variant[] = ${JSON.stringify(VARIANTS, null, 2)};

export const IDEAS: IdeaDetail[] = ${JSON.stringify(IDEAS, null, 2)};
`;

mkdirSync(resolve(FRONTEND, 'src/data'), { recursive: true });
writeFileSync(resolve(FRONTEND, 'src/data/catalogue.ts'), catalogue, 'utf8');

// --------------------------------------------------------------- artwork ----

const HUES = [140, 96, 200, 32, 168, 50, 262, 12, 122, 210];
const esc = (s: string) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function write(rel: string, body: string) {
  const target = resolve(MEDIA, rel);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, body, 'utf8');
}

function bottleGlyph(x: number, y: number, scale: number, stroke: string) {
  return `<g transform="translate(${x} ${y}) scale(${scale})" fill="none" stroke="${stroke}" stroke-width="2.4" stroke-linejoin="round">
    <path d="M14 2h12v6l5 9v27a4 4 0 0 1-4 4H13a4 4 0 0 1-4-4V17l5-9z"/>
    <path d="M9 24h22"/>
  </g>`;
}

